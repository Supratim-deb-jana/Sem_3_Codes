//WAP in JAVA for Casting
public class casting {
    public static void main(String[] args) {
        byte b1;
        int i=260;
        double d=23.75;
        float f=3.745f;
        System.out.println("Before Casting");
        System.out.println("i="+i);
        System.out.println("j="+d);
        System.out.println("f="+f);
        System.out.println("Integer to byte:");
        b1=(byte)i;
        System.out.println("(byte)i="+b1);
        System.out.println("Double to int");
        i=(int)d;
        System.out.println("(int)d="+i);
        System.out.println("float to int");
        i=(int)f;
        System.out.println("(int)f="+i);
    }
}
                     